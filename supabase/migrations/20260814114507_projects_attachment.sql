-- مرفقُ «مشاريعك السابقة» — ملفٌّ إلى جانب الرابط، لا بديلًا عنه.
--
-- طلبه وركفلو InterMission: «مشاريعك السابقة إن وجد (رفع ملف)». وكان
-- النموذج يعرض حقلَ رابطٍ واحدًا (`portfolio`) يجمع السيرةَ والمعرض، فمن
-- كان عملُه ملفًّا على جهازه لا رابطًا منشورًا لم يجد بابًا.
--
-- ⚠️ **في المستودع نفسِه `cv` تحت سابقة `projects/`.** مستودعٌ ثانٍ يعني
-- سياساتٍ ثانية وحدودَ صيغٍ ثانية ومسارَ تنزيلٍ ثانيًا يُصان — والملفّان
-- من صنفٍ واحد: مرفقٌ خاصٌّ لا يُخدَم إلّا برابطٍ موقَّت بعد فحص النطاق.
-- والسابقةُ تمنع أن يكتب أحدُهما فوق الآخر، فاسمُهما معرّفُ الصفّ نفسُه.
alter table public.applications
  add column if not exists projects_path text;

comment on column public.applications.projects_path is
  'مسار ملفّ المشاريع السابقة في مستودع `cv` تحت `projects/`. اختياريّ — والرابط البديل في `portfolio`';