-- وقتُ خروج بريد **القرار** — أختُ `receipt_mailed_at`، ودورُها أثقل.
--
-- **لماذا عمودٌ ثانٍ ولا يكفي الأوّل؟** ذاك يختم بريدَ «وصل طلبك» الذي
-- يخرج مرّةً لحظةَ التقديم؛ وهذا يختم بريدَ النتيجة الذي يخرج بعد المراجعة.
-- ولو جُمعا في عمودٍ واحدٍ لصار ختمُ الإيصال يقول «القرارُ أُرسل» — فيُحرم
-- كلُّ متقدّمٍ من نتيجته لأنه استلم إيصالًا.
--
-- ⚠️ **وهو حارسُ التكرار في الإرسال بالجملة.** بموسمٍ متوقَّعٍ يزيد على ٦٠٠
-- طلب، الرفضُ هو الأغلبية — بضع مئاتٍ من الرسائل. والإرسالُ يُنفَّذ على
-- دفعات (حدُّ المزوّد، ومهلةُ الدالّة)، فينقطع ويُستأنف. وبلا ختمٍ لكلّ
-- رسالةٍ خرجت، كلُّ استئنافٍ يبدأ من الصفر: يستلم المرفوضُ رفضَه مرّتين
-- وثلاثًا، ويُستنزف نصيبُ اليوم على من أُرسل إليه أصلًا.
--
-- والاستعلامُ الذي يقوده: `status='rejected' and decision_mailed_at is null`.
-- فالفهرسُ الجزئيّ أدناه يخدمه وحده ولا يزن شيئًا: صفوفُه تتناقص مع كل
-- دفعةٍ حتى يفرغ في آخر الموسم.
--
-- ⚠️ **ويُختم عند النجاح وحده.** لو خُتم قبل الإرسال لَضاع من فشل بريدُه
-- بلا أثر — وهو الصنف الذي عطّل التقديم مرّتين: **فشلٌ لا يصرخ**. والغياب
-- يقول «لم يخرج»، وأمّا «لماذا» فموضعُه لوحةُ Resend لا عمودٌ هنا.
--
-- ⚠️ **ولا يُصفَّر عند تغيير الحالة.** من رُفض وأُرسل إليه ثم أُعيدت حالتُه
-- إلى «قيد المراجعة» ثم رُفض ثانيةً، يبقى ختمُه — فلا يُرسل إليه رفضٌ
-- ثانٍ بلا قصد. وإعادةُ الإرسال المتعمَّدة تُصفّر العمود يدويًّا، وهي
-- حالةٌ نادرةٌ تستحقّ قرارًا لا تلقائيّة.

alter table public.applications
  add column if not exists decision_mailed_at timestamptz;

comment on column public.applications.decision_mailed_at is
  'وقت خروج بريد القرار (الرفض غالبًا). null = لم يخرج — والسبب في لوحة Resend.';

create index if not exists applications_pending_decision_mail_idx
  on public.applications (status)
  where decision_mailed_at is null;
