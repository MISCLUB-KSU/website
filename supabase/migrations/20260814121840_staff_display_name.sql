-- اسمُ الداخل — للترحيب به في اللوحة.
--
-- ⚠️ **وهو استثناءٌ من قاعدة «لا أسماء» لا نقضٌ لها.** القاعدة تحكم ما
-- **يُنشر**: الصفحات والمستندات وبياناتها. واللوحة صفحةٌ داخلية خلف تسجيل
-- دخول و`noindex`، لا يقرؤها إلّا صاحبُ الاسم ومن معه في الطاقم. ولذلك
-- بقي `label` على حاله وصفًا للدور — فهو الذي يظهر في مواضع أخرى.
--
-- ولا يُستعمل في فرزٍ ولا في تصدير: غرضُه سطرُ ترحيبٍ واحد.
alter table public.staff
  add column if not exists display_name text;

comment on column public.staff.display_name is
  'اسم الداخل للترحيب في اللوحة وحدها — صفحة داخلية خلف دخول. و`label` يبقى وصف الدور';