-- وقتُ خروج بريد «وصل طلبك» — وغيابُه هو الإشارة.
--
-- **لماذا عمودٌ أصلًا؟** فشلُ البريد لا يُسقط الطلب عمدًا (`email/client.ts`):
-- أن يصل الطلبُ بلا إشعارٍ خيرٌ من أن يُردَّ الطالب بعد ثلاث خطوات. لكنّ
-- ثمنَ ذلك أن الفشل **لا يظهر إلا في سجلّ الخادم**، ولا أحد يفتحه يوميًّا.
--
-- وقد وقع هذا فعلًا في ١٥ أغسطس ٢٠٢٦: خرج الطلبُ ووصل صفُّه، وردّ Resend
-- «النطاق غير موثَّق» — فلم يعلم أحدٌ إلا بقراءة السجلّ بعدها بساعة. وهو
-- نفسُ صنفِ العطل الذي عطّل التقديمَ يومًا كاملًا قبله: **فشلٌ لا يصرخ**.
--
-- فيُختم الوقتُ عند النجاح، وتَعُدُّ اللوحةُ من بقي `null` وتعرضه رقمًا في
-- أعلى الشاشة (`admin/page.tsx`). فيصير الصمتُ عددًا يُرى.
--
-- ⚠️ **ولا يُقيَّد سببُ الفشل هنا.** عمودٌ للسبب يغري بقراءته بدل قراءة
-- سجلّ Resend — وهو أدقُّ منه دائمًا وأحدثُ. فالغيابُ يقول «لم يخرج»،
-- وأمّا «لماذا» فموضعُه لوحةُ المزوّد.
--
-- ⚠️ **والقديمُ يبقى `null`**، وهو صادقٌ فيه: لم يُقيَّد له وقتٌ لأن العمود
-- لم يكن موجودًا. والجدول كان قد أُفرغ من الصفوف التجريبية في اليوم نفسِه،
-- فلا صفَّ سابقٌ يشوّش العدّ.

alter table public.applications
  add column if not exists receipt_mailed_at timestamptz;

comment on column public.applications.receipt_mailed_at is
  'وقت خروج بريد «وصل طلبك». null = لم يخرج — والسبب في لوحة Resend.';
