import { Injectable } from "@angular/core";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";

import { environment } from "../../environments/environment";

/**
 * عميلُ Supabase — **واحدٌ للتطبيق كلِّه**.
 *
 * ⚠️ **ولا يُنشأ عميلٌ ثانٍ في أي مكان.** `createClient` تفتح لكل نسخةٍ
 * مستمعَ تغيّرِ جلسةٍ ومؤقّتَ تجديدِ رمز، فنسختان تتسابقان على تجديد
 * الرمز نفسِه — والخاسرُ يحمل رمزًا بطل، فتُردّ استعلاماتُه 401 بلا سبب
 * ظاهر. ولهذا هي `providedIn: "root"`، وكلُّ خدمةٍ تحقنها.
 *
 * ── لماذا يكفي المتصفّحُ وحده هنا ────────────────────────────────────────
 *
 * ⚠️ **الأمانُ في القاعدة لا في التطبيق.** لوحةُ Next تستعلم `select("*")`
 * بلا شرطٍ واحد، والذي يقصّ الصفوف هو `RLS`: قائدُ اللجنة يستقبل صفوفَ
 * نطاقه، ومن ليس في `staff` يستقبل **صفرًا**. فلا تعتمد سلامةُ البيانات
 * على وجود خادمٍ بيننا وبين القاعدة — ولو اعتمدت لكانت لوحةُ Next نفسُها
 * قابلةً للتجاوز باستدعاءٍ مباشر.
 *
 * ولهذا يصحّ أن يقرأ تطبيقُ متصفّحٍ مباشرةً بالمفتاح العامّ: **هو لا يمنح
 * شيئًا**، والجلسةُ هي ما يُعرّف القارئ. ومن فتح اللوحة بلا جلسة يرى
 * صفرَ صفوفٍ لا لأننا أخفيناها، بل لأن القاعدة لم تُعطها.
 *
 * ⛔ **ويبقى شيئان خارج المتصفّح**: إرسالُ بريد القرار (مفتاح Resend)،
 * وإنشاءُ روابط التحميل الموقَّعة إن لم تسمح بها سياساتُ التخزين للعميل.
 * كلاهما يبقى في مشروع Next أو ينتقل إلى دالّة حافّة — ولا يُحلّ بجلب
 * مفتاحٍ سرّيّ إلى هنا.
 */
@Injectable({ providedIn: "root" })
export class SupabaseClientService {
  readonly client: SupabaseClient = createClient(
    environment.supabaseUrl,
    environment.supabasePublishableKey,
    {
      auth: {
        /* الجلسةُ تُحفظ وتُجدَّد وحدها — القائد لا يسجّل دخولًا كل ساعة */
        persistSession: true,
        autoRefreshToken: true,
        /* ⚠️ **يقرأ الرابطَ عند العودة من بريد الدخول.** رابطُ السحر يعود
           بالرمز في **الشُّظيّة** (`#access_token=…`)، وبدون هذا تبقى
           الصفحةُ على شاشة الدخول والرمزُ في العنوان بلا من يقرؤه. */
        detectSessionInUrl: true,
        flowType: "pkce",
      },
    },
  );
}
