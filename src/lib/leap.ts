import { z } from "zod";

import { normalizeDigits } from "@/lib/registration";

/**
 * قواعد التحقّق من تسجيل حضور LEAP 2026.
 *
 * خمسةُ حقولٍ لا سادس — هذا كلُّ ما طلبه المنظِّم، ولا يُضاف حقلٌ «قد
 * ينفع لاحقًا»: كلُّ حقلٍ زائدٍ في نموذجِ تحويلٍ يُسقط مسجِّلين.
 *
 * التحقّق يُنفَّذ على الخادم دائمًا — ما في المتصفّح راحةٌ للطالب لا حاجزُ
 * أمان، ومن يعطّل الجافاسكربت يصل إلى الإجراء مباشرةً بإرسالٍ عاديّ.
 */

/** حروفٌ عربيةٌ وتشكيلٌ ومسافات — بلا لاتينيّ وبلا أرقامٍ من أي نوع */
const ARABIC_ONLY = /^[ء-ْ\s]+$/;

/** حروفٌ لاتينيةٌ ومسافاتٌ وفاصلةٌ عليا وشرطة — أسماءٌ مثل `Al-Otaibi` و`O'Neil` */
const LATIN_NAME = /^[A-Za-z][A-Za-z'\-. ]*$/;

/**
 * رقمُ الحجز من رسالة LEAP — `Unique Reference Number`.
 *
 * ⚠️ **يُتحقَّق منه بتساهلٍ عمدًا، ولا يُفرض عليه شكلٌ مخترَع.** صيغةُ
 * الرقم عند LEAP غيرُ موثَّقةٍ لنا: ما رأيناه في رسالةٍ حقيقيةٍ واحدةٍ
 * كان محجوبًا. وفرضُ نمطٍ مبنيٍّ على تخمينٍ (طولٌ ثابت، أو حروفٌ ثم أرقام)
 * يعني ردَّ مسجِّلٍ يحمل تذكرةً صحيحة — وهو عطلٌ صامتٌ لا يكتشفه إلا من
 * وقع فيه، ولن يعود.
 *
 * فالمقبول: خانةٌ إلى اثنتين وثلاثين، حروفٌ لاتينيةٌ وأرقامٌ وشرطة.
 * ويبقى التفرّد حارسَ التكرار في قاعدة البيانات لا هذا النمط.
 */
const REFERENCE = /^[A-Za-z0-9-]{4,32}$/;

/**
 * الأرقام الهنديّة تُحوَّل قبل الفحص — الطالب ينسخ رقمه من رسالةٍ أو من
 * لوحةِ مفاتيحَ عربية، فيصل `٠٥٥…` ويُردّ بحجّة «أرقام فقط» وهو صحيح.
 */
export const leapSchema = z.object({
  nameAr: z
    .string()
    .trim()
    .min(1, "اكتب اسمك بالعربي")
    .min(5, "اكتب اسمك كاملًا بالعربي")
    .max(60, "الاسم أطول من اللازم")
    .regex(ARABIC_ONLY, "اسمك بالعربي حروفٌ عربية فقط"),

  nameEn: z
    .string()
    .trim()
    .min(1, "اكتب اسمك بالإنجليزي")
    .min(5, "اكتب اسمك كاملًا بالإنجليزي")
    .max(60, "الاسم أطول من اللازم")
    .regex(LATIN_NAME, "اسمك بالإنجليزي حروفٌ لاتينية فقط"),

  email: z
    .string()
    .trim()
    .toLowerCase()
    .min(1, "اكتب بريدك")
    .email("تأكد من صيغة البريد")
    .max(120, "البريد أطول من اللازم"),

  /* يبدأ بـ 05 ومجموعه عشر خانات — نفسُ قاعدةِ نموذج العضوية */
  phone: z
    .string()
    .transform(normalizeDigits)
    .pipe(
      z
        .string()
        .min(1, "اكتب رقم جوالك")
        .regex(/^\d+$/, "رقم الجوال أرقام فقط")
        .length(10, "رقم الجوال عشر خانات")
        .startsWith("05", "رقم الجوال يبدأ بـ 05"),
    ),

  /* يُخزَّن بحروفٍ كبيرةٍ موحَّدة — فهرسُ التفرّد يقارن كذلك */
  reference: z
    .string()
    .trim()
    .toUpperCase()
    .min(1, "اكتب رقم الحجز")
    .regex(REFERENCE, "رقم الحجز حروفٌ لاتينية وأرقام، بلا مسافات"),
});

export type LeapInput = z.infer<typeof leapSchema>;

/**
 * **بابُ التسجيل — مفتاحٌ واحدٌ يقرأه الخادمُ والواجهةُ معًا.**
 *
 * `false` يُغلقه: النموذجُ يُستبدل بإعلانِ إغلاق، والإجراءُ يردّ كلَّ إرسالٍ
 * يصله. والمفتاحُ واحدٌ لا اثنان عمدًا — لو أُخفي النموذجُ وحدَه لبقي
 * الإجراءُ يقبل من عطّل الجافاسكربت أو أرسل مباشرةً، ولو حُرس الإجراءُ
 * وحدَه لملأ الطالبُ خمسةَ حقولٍ ثم رُدَّ في وجهه.
 *
 * ولا يُحذف الكودُ عند الإغلاق: الفعاليةُ سنويّة، والفتحُ في العام القادم
 * تبديلُ هذا السطر.
 */
export const LEAP_REGISTRATION_OPEN = false;

/** ما يُقال حين يكون البابُ مغلقًا — نصٌّ واحدٌ للواجهة وللإجراء */
export const LEAP_CLOSED_MESSAGE =
  "التسجيل مقفل — انتهت مهلة تسجيل الحضور مع النادي.";

/** أسماءُ الحقول كما تخرج من `FormData` — مصدرٌ واحدٌ للنموذج وللإجراء */
export const LEAP_FIELDS = [
  "nameAr",
  "nameEn",
  "email",
  "phone",
  "reference",
] as const;

export type LeapField = (typeof LEAP_FIELDS)[number];

export type LeapState = {
  /** `idle` قبل أي إرسال — لتمييزِ «لم يُرسَل بعد» عن «أُرسل ونجح» */
  status: "idle" | "error" | "done";
  /** رسالةٌ عامّةٌ لا تخصّ حقلًا بعينه (تعذّرَ الحفظ، تذكرةٌ مسجَّلة) */
  message?: string;
  errors: Partial<Record<LeapField, string>>;
  /**
   * ⚠️ **ما كتبه الطالب يُعاد إليه عند الخطأ.** نموذجٌ من خمسةِ حقولٍ
   * يُفرَّغ عند أول خطأ يعني إعادةَ كتابةِ اسمين وبريدٍ وجوّالٍ ورقمِ حجزٍ
   * يُنسخ من رسالة — وهذا وحده يكفي ليغادر المسجِّل.
   */
  values: Partial<Record<LeapField, string>>;
};

export const emptyLeapState: LeapState = {
  status: "idle",
  errors: {},
  values: {},
};

/** ما يُعاد ملؤه بعد الخطأ */
export function echoLeap(formData: FormData): LeapState["values"] {
  const out: LeapState["values"] = {};
  for (const field of LEAP_FIELDS) {
    const value = formData.get(field);
    if (typeof value === "string") out[field] = value;
  }
  return out;
}
