"use client";

import Link from "next/link";
import { useEffect, useState } from "react";

/**
 * ترحيبُ الشريط — يظهر للقائد الداخل وحده، وطريقٌ إلى اللوحة من أي صفحة.
 *
 * ⚠️ **يُسأل في المتصفّح لا على الخادم.** قراءةُ الجلسة في الصفحة تحوّلها
 * من ثابتةٍ إلى مبنيّةٍ لكل طلب — فيبطؤ الموقع على كل الطلاب لأجل سطرٍ
 * يراه القادة. فالصفحةُ تبقى ثابتة، والسؤال يقع بعد التحميل.
 *
 * ⚠️ **ولا يحجز مكانًا قبل أن يعرف.** لا هيكلَ تحميلٍ ولا مساحةٌ محفوظة:
 * أكثرُ من يمرّ زائرٌ لا جلسة له، فحجزُ مكانٍ يزيح الشريط عند كل زيارة —
 * وهو `CLS` مقابل لا شيء. ومن له اسمٌ يظهر سطرُه بلا إزاحةٍ تُذكر لأنه
 * في طرفٍ مرن.
 *
 * ⚠️ **ولا يُعرض شيءٌ عند الفشل.** انقطاعُ الشبكة أو ردٌّ غير متوقَّع
 * يُترك صامتًا: هذا سطرُ راحةٍ لا وظيفةٌ يُنتظر منها جواب.
 */
export function StaffGreeting({ className = "" }: { className?: string }) {
  const [name, setName] = useState<string | null>(null);

  useEffect(() => {
    /**
     * ⚠️ **لا يُسأل الخادمُ إلّا لمن معه كوكي جلسة.**
     *
     * كان السؤال يقع **لكلّ زائر**: كلُّ طالبٍ يفتح الرئيسية يوقظ دالّةً
     * خادمةً (`/api/me`, `cache: MISS`) ليُقال له «لست من الطاقم». وهي
     * الطلبُ الأخير في الصفحة — قِيس على جوّالٍ مخنوق: يبدأ بعد ٣٫٣ ثانية
     * ويمدّ ذيلَ التحميل، وينافس الخطوطَ على النطاق.
     *
     * وفي موسمٍ متوقَّعٍ يزيد على ٦٠٠ متقدّم، هذا استدعاءُ دالّةٍ لكلّ
     * زيارةِ صفحةٍ من كلّ زائر — كلفةٌ ووقتٌ مقابل سطرٍ يراه سبعةُ أنفار.
     *
     * وكوكي Supabase (`sb-<ref>-auth-token`) ليس `HttpOnly` — تكتبه
     * المكتبةُ ليقرأه عميلُ المتصفّح — فوجودُه يُقرأ من هنا بلا طلبٍ شبكيّ.
     *
     * ⚠️ **وهو ترشيحٌ لا تحقّق:** كوكيٌّ منتهٍ أو مزوَّرٌ يمرّ من هذا الشرط،
     * ثم يردّه `/api/me` على الخادم كما كان. الأمانُ هناك، وهذا توفيرٌ فقط.
     */
    if (!document.cookie.includes("-auth-token")) return;

    /* يُلغى عند التفكيك حتى لا تُضبط الحالة على مكوّنٍ رحل */
    const stop = new AbortController();

    fetch("/api/me", { signal: stop.signal })
      .then((r) => (r.ok ? r.json() : null))
      .then((data: { name?: string | null } | null) => {
        if (typeof data?.name !== "string") return;
        setName(data.name);
        /**
         * ⚠️ **يُحفظ ليقرأه لوحُ التحميل قبل أوّل رسم.**
         *
         * اللوحُ وسمٌ ساكن ينسحب بعد ٩٥٠ms، وهذا الاسمُ يصل من الشبكة —
         * فلا يلحقه أبدًا في أوّل زيارة. والمحفوظُ هنا يُقرأ في السطر
         * `beforeInteractive` فيظهر فورًا في الزيارات التالية.
         *
         * ولا يُقرأ إلّا مع كوكي جلسةٍ قائمة (انظر `CURTAIN_INIT_SCRIPT`)،
         * فمن خرج لا يُحيّا باسمه على جهازٍ يشاركه غيرُه.
         */
        try {
          localStorage.setItem("mis-hail", data.name.trim().split(/\s+/)[0]);
        } catch {
          /* تخزينٌ ممنوع أو ممتلئ — اللوحُ يبقى بلا اسم، ولا شيء يسقط */
        }
      })
      .catch(() => {
        /* صامتٌ عمدًا — انظر رأس الملفّ */
      });

    return () => stop.abort();
  }, []);

  if (!name) return null;

  /**
   * ⚠️ **الاسمُ الأول وحده — وهو إصلاحُ تخطيطٍ قبل أن يكون ذوقًا.**
   *
   * الشريطُ يعطي الكتلةَ اليسرى ٢٦٥ بكسلًا، ومحتواها بلا ترحيبٍ ١٦٥.
   * فاسمٌ كامل («عبدالرحمن بن عبدالعزيز الشمري») يتجاوزها فيلتفّ زرُّ
   * التقديم إلى صفٍّ ثانٍ ويصير الشريطُ ١١٤ بكسلًا بدل ٦٢ — مقيسٌ عند
   * ١٠٢٤ و١٢٨٠ و١٤٤٠.
   *
   * و«أهلًا حسام» أدفأ من «أهلًا حسام المطيري» في كلّ حال: التحيّةُ
   * بالاسم الأول لا باللقب.
   */
  const first = name.trim().split(/\s+/)[0];

  /* ⚠️ **لا `display` في الأساس — يأتي من موضعه.** الشريط يريده `inline-flex`
     ولوحةُ الجوّال تريده `flex w-full`، وهما صنفان في طبقةٍ واحدة: لو ثبت
     أحدُهما هنا لغلب أو غُلب بترتيب الملفّ لا بنيّة الموضع — فيصير الصنف
     المُمرَّر يعمل أحيانًا ويُهمَل أحيانًا، وهو أسوأ من ألّا يعمل. */
  return (
    <Link
      href="/admin"
      /* ⚠️ `min-w-0` مع `truncate` شبكةُ أمانٍ لا زينة: الاسمُ الأول قصيرٌ
         في الغالب، لكنّ اسمًا أوّلَ طويلًا جدًّا كان سيعيد الالتفافَ نفسَه.
         فيتقلّص بنقاطٍ ثلاث ويبقى الشريطُ صفًّا واحدًا. */
      className={`text-fg-muted hover:text-fg min-h-11 min-w-0 items-center truncate text-sm transition-colors ${className}`}
    >
      أهلًا {first}
    </Link>
  );
}
