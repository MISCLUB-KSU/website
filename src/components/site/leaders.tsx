import type { CSSProperties } from "react";

import { LEADERS } from "@/content/people";

/**
 * القيادات — **الشعار مفكوكًا إلى تسلسل**.
 *
 * ⚠️ **يحذف نفسه ما دامت `LEADERS` فارغة.** القائمة فارغةٌ عمدًا: نشر أسماء
 * الأشخاص يحتاج قرارًا من الرئاسة **وموافقة كل شخص** — رأس `content/people.ts`.
 *
 * ── الفكرة ─────────────────────────────────────────────────────────────
 *
 * الصفحة اسمها «هيكلة النادي»، فالشكل يرسم الهيكل بدل أن يزيّنه:
 *
 * ١) **الزاوية محورُ التخطيط لا زخرفةٌ على صندوق.** كل صفٍّ يتزحزح عن الذي
 *    فوقه بمقدار `ارتفاع الصفّ × tan(24°)` بالضبط، فتنحدر الأسماء قُطريًّا
 *    بزاوية الشعار نفسها. الانحدار **مشتقٌّ حسابيًّا** من `--rake-tan`، فلو
 *    صُحّحت زاوية الشعار يومًا تبعها الانحدار وحده.
 * ٢) **ضلعٌ قائم على حافّة كل صفّ**، بارتفاع الصفّ كاملًا. والأضلاع
 *    المتدرّجة تُقرأ معًا شعارَ النادي مفكوكًا — ستّة أضلاعٍ متوازية
 *    منحدرة، وهي هيئة الشعار بالحرف.
 * ٣) **بلا صناديق ولا حدود ولا أركانٍ مقصوصة.** النسخة السابقة كانت نسخةً
 *    من بطاقة اللجنة أسفل الصفحة — «إعادة تدوير أسلوبك» لا تصميم. رُفضت:
 *    «انت متمسك بالهوية مره… ابتكر» (الإدارة، ٧ أغسطس ٢٠٢٦). الفراغ والمقاس
 *    يفصلان الصفوف، لا الإطارات.
 *
 * ── حواجز مقصودة ───────────────────────────────────────────────────────
 *
 * ⚠️ **الانحدار محدود بـ`min()`**: بلا سقفٍ تخنق اثنتا عشرة قيادةً النصَّ
 * بانزياحٍ 313px على الشاشة المتوسّطة. السقف `12rem` (192px) يستوعب سبعة
 * صفوفٍ منحدرة — وهو عدد القيادات المتوقّع (رئيس + نائب + خمس لجان) —
 * ثم يستوي ما زاد فيبقى الشكل مقروءًا مهما كبر العدد. جُرِّب `7rem` أوّلًا
 * فسطّح الانحدار بعد الصفّ الرابع وضاع التوقيع على أكثر الصفوف.
 *
 * ⚠️ **يُلغى تمامًا على الجوّال** (`sm:` وحدها تُفعّله): 390px لا تحتمل
 * انزياحًا أفقيًّا، ولو بقي لانضغط الاسم في عمودٍ نحيل.
 *
 * ⚠️ **بلا حركة دخول.** الأسماء مرئيّةٌ افتراضًا — لا `opacity: 0` تنتظر
 * حدثًا قد لا يقع. الحركة الوحيدة إزاحةُ ضلعٍ عند المرور.
 *
 * ⚠️ **بلا صور وبلا ترقيم.** الصورة إذنٌ ثانٍ غير إذن الاسم، والرقم على
 * القياديّين يُقرأ رتبةً — والانحدار نفسه يؤدّي معنى التسلسل بلا رقم.
 */

/** tan(24°) — نظير `--rake-tan` في `globals.css`. مكرَّرٌ هنا لأنه ثابتٌ
    يُحسب وقت البناء لا خاصيّةَ CSS حيّة (نفس مبرِّر `RAKE_TAN` في
    `project-index.tsx` و`VIEWBOX_W` في `mark-morph.tsx`). */
const RAKE_TAN = 0.4452;

/** ارتفاع الصفّ المرجعيّ الذي يُشتقّ منه الانزياح — يطابق `min-h` أدناه. */
const ROW_H = 64;

/** انزياح كل صفٍّ عن سابقه: الارتفاع × tan(24°) = 28.5px. الرقم **محسوبٌ**
    لا مكتوبٌ بيد، فالانحدار هو زاوية الشعار بالضبط لا ما يقاربها. */
const STEP = Number((ROW_H * RAKE_TAN).toFixed(2));

export function Leaders() {
  if (LEADERS.length === 0) return null;

  return (
    <section aria-labelledby="leaders-heading" className="mb-s9">
      {/* العنوان يجلس على رأس الانحدار — أوّل صفٍّ تحته يبدأ من محاذاته،
          ثم تنحدر البقيّة عنه. فيُقرأ رأسَ التسلسل لا وسمًا معلّقًا فوقه. */}
      <h2
        id="leaders-heading"
        className="font-display text-sm font-semibold tracking-[0.15em] text-fg-muted"
      >
        القيادات
      </h2>

      <ul className="mt-s6">
        {LEADERS.map((person, index) => {
          const row = (
            <>
              {/* الضلع القائم — بارتفاع الصفّ كاملًا (`self-stretch`).
                  الغلاف مستقيمٌ والميلان في ابنه: `.mis-slant` يَجُزّ
                  (`skewX`) فيتمدّد الصندوق المحيط، والغلاف الثابت يمنع
                  ذلك من تحريك النصّ بعده. */}
              <span aria-hidden className="w-3 shrink-0 self-stretch">
                <span className="mis-slant block h-full w-full bg-mark-quiet transition-colors group-hover:bg-accent" />
              </span>

              <span className="flex min-w-0 flex-col justify-center py-s2">
                <span className="font-display text-xs font-semibold tracking-[0.12em] text-fg-muted">
                  {person.role}
                </span>
                <span className="mt-s1 text-balance font-display text-xl font-bold text-fg transition-colors group-hover:text-accent sm:text-2xl">
                  {person.name}
                </span>

                {person.linkedin ? (
                  /* ⚠️ ملتصقٌ بالاسم لا مدفوعًا إلى طرف الصفّ. النسخة الأولى
                     وضعته على `ms-auto` فانفتح بينه وبين الاسم خليجٌ بعرض
                     الصفحة — «المحتوى مرميّ على الحواف»، وهو ما يكسر
                     الانحدار: العين تتبع قُطرًا فتجد الصفّ ممتدًّا أفقيًّا.
                     العنقود الملتصق يجعل كل صفٍّ كتلةً واحدة تنحدر. */
                  <span className="mt-s1 inline-flex min-h-11 items-center gap-s2 self-start text-sm font-medium text-fg-muted transition-colors group-hover:text-accent">
                    لينكدإن
                    {/* ضلعٌ صغير مؤشّرًا للرابط — لا سهمٌ من حزمة أيقونات ولا
                        شعار لينكدإن: العلامة التجارية لا تُعاد صياغتها. عارٍ
                        بلا صندوق. يزحف للخارج عند المرور: `-translate-x`
                        فيزيائيّة والصفحة RTL فطرفُ السطر التالي هو اليسار،
                        أي أن السالب «إلى الخارج». وTailwind v4 يكتبها في
                        خاصيّة `translate` المستقلّة لا في `transform`، فلا
                        تمحو `skewX` الذي يصنع الميلان. معطّلةٌ لمن طلب
                        تقليل الحركة. */}
                    <span
                      aria-hidden
                      className="mis-slant inline-block h-3.5 w-1 shrink-0 bg-current transition-transform motion-safe:group-hover:-translate-x-1 motion-reduce:transition-none"
                    />
                  </span>
                ) : (
                  /* ⚠️ **تُحجز الخانة ولا تُطوى.** من لا رابط له كان صفّه
                     68px مقابل 116 لإخوته (مقيسًا)، فينكسر الخطّ القُطريّ
                     عنده: ضلعُه أقصر والانحدار يتعثّر في منتصفه. والقاعدة
                     في تركيبٍ متوازٍ أن الخانة الغائبة **تُحجز** لا تُطوى،
                     فيبقى الإيقاع واحدًا مهما نقص المحتوى. */
                  <span aria-hidden className="mt-s1 block min-h-11" />
                )}
              </span>
            </>
          );

          return (
            <li
              key={person.name}
              /* ⚠️ الانزياح يُمرَّر **خاصيّتَي CSS** لا صنفًا مُركَّبًا:
                 Tailwind يمسح النصوص **الحرفيّة** في المصدر، فصنفٌ مبنيٌّ
                 بقالبٍ نصّي (`ms-[...${'$'}{STEP}px...]`) لا يُولَّد أبدًا
                 ويسقط الانحدار صامتًا. الصنف أدناه حرفيٌّ ثابت، والقيمتان
                 المتغيّرتان تدخلانه عبر `--i` و`--step` — فيبقى `STEP`
                 مشتقًّا من `RAKE_TAN` ويبقى الصنف قابلًا للكشف. */
              /* ⚠️ **بلا خطٍّ فاصل بين الصفوف.** جُرِّب `border-t` فصارع
                 الانحدار: خطوطٌ أفقيّةٌ ممتدّة بعرض الصفحة تحت تركيبٍ
                 قُطريّ = محورانِ متعاكسان في مساحةٍ واحدة، فينكسر الشكل.
                 الفصل يأتي من الفراغ وميلان الأضلاع المتدرّجة وحدها. */
              style={{ "--i": index, "--step": `${STEP}px` } as CSSProperties}
              className="sm:ms-[min(calc(var(--i)*var(--step)),12rem)]"
            >
              {person.linkedin ? (
                <a
                  href={person.linkedin}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="group flex min-h-16 items-stretch gap-s4"
                >
                  {row}
                </a>
              ) : (
                /* بلا رابط: نفس الصفّ ونفس المحاذاة، بلا حالة مرورٍ كاذبة
                   تُوهم أنه قابلٌ للنقر. */
                <div className="flex min-h-16 items-stretch gap-s4">{row}</div>
              )}
            </li>
          );
        })}
      </ul>
    </section>
  );
}
