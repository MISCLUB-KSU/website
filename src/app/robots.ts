import type { MetadataRoute } from "next";

import { SITE_URL } from "@/lib/site";

/**
 * `robots.txt` — أول ما يقرأه الزاحف قبل أن يدخل.
 *
 * ⚠️ **بوّابةٌ خشنة تسبق `noindex` لا تُغني عنها.** صفحاتُ اللوحة والروابط
 * المباشرة تحمل `robots: { index: false }` في بياناتها الوصفية، لكن ذلك
 * يمنع **الفهرسة بعد الزحف**؛ وهذا يمنع **الزحف من أصله**. والاثنان معًا،
 * لأن أحدهما وحده يترك بابًا:
 *
 * · بـ`noindex` وحده يزحف الزاحف على `/admin` ويطلب صفحاته.
 * · بـ`Disallow` وحده قد يُفهرس العنوان إن أشار إليه رابطٌ خارجيّ — فالزاحف
 *   لم يدخل ليقرأ `noindex`. ولهذا يبقى `noindex` في الصفحات.
 *
 * ── ما يُمنع ولماذا ──────────────────────────────────────────────────────
 * · `‎/admin` — لوحةُ بيانات المتقدّمين. لا شأن لمحرّك بحثٍ بها.
 * · `‎/join/project/…` و`‎/join/committee/…` — روابطُ تقديمٍ **موجَّهة**
 *   لجمهور قائدٍ بعينه. فهرستُها تجعلها بابًا عامًّا موازيًا للنموذج
 *   الرسميّ، فتنقسم الطلبات بلا قصد وتُحسب كأنها مفاضلة.
 * · `‎/auth` — مسارُ تأكيد الدخول، عناوينُه لمرّةٍ واحدة.
 *
 * و`‎/join` نفسه **مسموح**: هو الباب الذي نريد أن يُعثر عليه.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: "*",
        allow: "/",
        disallow: ["/admin", "/auth", "/join/project/", "/join/committee/"],
      },
    ],
    sitemap: `${SITE_URL}/sitemap.xml`,
    host: SITE_URL,
  };
}
