const HELP_WHATSAPP_RAW = process.env.NEXT_PUBLIC_JOIN_HELP_WHATSAPP ?? "";

/** أرقامٌ فقط — فمسافةٌ أو `+` تسرّبت إلى المتغيّر تكسر الرابط صامتةً */
export const HELP_WHATSAPP = HELP_WHATSAPP_RAW.replace(/\D/g, "");

/** رابطُ محادثةٍ بنصٍّ مبدئيّ — و`null` حين لا رقمَ مضبوط */
export function helpWhatsappHref(text: string): string | null {
  if (!HELP_WHATSAPP) return null;
  return `https://wa.me/${HELP_WHATSAPP}?text=${encodeURIComponent(text)}`;
}
