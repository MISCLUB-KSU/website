/**
 * حالاتُ الطلب — **مصدرٌ واحدٌ تقرؤه اللوحتان والقاعدةُ تفرضه**.
 *
 * ⚠️ **وُلد هذا الملفّ من عطبٍ وقع فعلًا.** كانت لوحة Angular تحمل نسختَها
 * الخاصّة، فافترقت عن نسخة Next في ثلاثة مواضع خلال شهرٍ واحد:
 *
 *   · فيها `shortlisted` — **وقيدُ القاعدة يرفضها**، فاختيارُها يردّ بخطأ
 *   · وليس فيها `referred` — وهي الحالةُ التي وعدت بها الإدارةُ القادة
 *   · وتقول «مرفوض» حيث تقول الأخرى «معتذَر عنه» — والتلطيفُ كان مقصودًا
 *
 * ولم ينكشف شيءٌ من ذلك إلّا بلقطةٍ عابرة. فالقائمةُ هنا، والملفُّ **بياناتٌ
 * صرفة بلا استيرادٍ يخصّ إطارًا** — فيقرؤه Next وAngular معًا كما يقرآن
 * `preferences.ts`.
 *
 * ⚠️ **والقائمةُ تُطابق قيد القاعدة حرفًا بحرف** (`applications_status_check`
 * في هجرة `status_referred_to_second_choice`). زيادةٌ هنا بلا هجرة تُرمى
 * بخطأٍ غامض، ونقصٌ يمنع حالةً مشروعة.
 */

export type ApplicationStatus = {
  value: string;
  label: string;
  /** متغيّرُ لونٍ في `dash.css` — تقرؤه لوحة Next، وتتجاهله Angular */
  color: string;
};

/**
 * الترتيبُ **مقيسٌ لا مذوَّق.**
 *
 * قاس مدقّقُ `dataviz` الأزواجَ المتجاورة: بترتيب (جديد · مراجعة · مقبول ·
 * معتذَر) يتلاصق الأخضر والأحمر فيهبط الفصلُ إلى ΔE 7.2 عند عمى الأحمر —
 * داخل نطاق الخطر. وبهذا الترتيب يصير أسوأُ زوجٍ (كهرماني↔أخضر) عند 8.2،
 * ويجتاز. **لا يُعاد الترتيب بلا إعادة القياس.**
 *
 * ولأن الأخضر والمحايد يسقطان في «أرضية التشبّع» (يُقرآن رماديين)، فكلُّ
 * حالةٍ تحمل اسمها نصًّا دائمًا — اللونُ ثانويٌّ لا وحيد.
 */
export const APPLICATION_STATUSES: readonly ApplicationStatus[] = [
  { value: "accepted", label: "مقبول", color: "var(--st-accepted)" },
  { value: "reviewing", label: "قيد المراجعة", color: "var(--st-reviewing)" },
  { value: "new", label: "جديد", color: "var(--st-new)" },
  /**
   * ⚠️ **باقيةٌ في القيد ولا تُستعمل بعد اليوم.** كانت تعني «محال إلى
   * الرغبة الثانية» قبل عمود `stage`؛ والنزولُ صار `stage + 1`. ولا تُحذف
   * من القيد لأن حذفَ قيمةٍ من قيدٍ حيٍّ يحتاج هجرةً لا داعيَ لخطرها.
   */
  { value: "referred", label: "محال للثانية", color: "var(--st-referred)" },
  /**
   * ⛔ **لا تُضبط بزرّ.** صارت تعني «انتهت رغباتُه كلُّها» — وهو حكمٌ لا
   * يملكه قائدٌ واحد؛ هو يقول «لا يناسب لجنتي» والقاعدةُ تعرف هل بعدها
   * رغبةٌ أخرى. ومسارُها الوحيد دالّةُ `pass_over`.
   */
  { value: "rejected", label: "معتذَر عنه", color: "var(--st-rejected)" },
];

/**
 * ما يضبطه القائدُ **مباشرةً** — والثلاثةُ وحدها.
 *
 * يُفحص في `admin/actions.ts` على الخادم أيضًا: إخفاءُ زرٍّ ليس منعًا.
 */
export const DIRECT_STATUSES: readonly string[] = [
  "new",
  "reviewing",
  "accepted",
];

/** وسمُ الحالة للعرض — والمجهولةُ تُعرض كما هي لا تُبتلع صامتة */
export function statusLabel(value: string): string {
  return (
    APPLICATION_STATUSES.find((s) => s.value === value)?.label ?? value
  );
}

/**
 * الحالاتُ التي **يمكن أن تقع فعلًا** — بلا `referred`.
 *
 * ⚠️ **وحذفُها من العرض ليس تجميلًا.** بعد عمود `stage` صار النزولُ
 * `stage + 1` لا حالةً، فـ`referred` لا تُكتب في صفٍّ أبدًا — ورسمُها في
 * حلقة «أين وصلت المراجعة» يعرض شريحةً صفريّةً للأبد. والصفرُ الدائم في
 * لوحةٍ يُقرأ **«لم يُحَل أحدٌ بعد»** لا «هذي الحالة لم تعد تُستعمل» —
 * فينتظر القائدُ رقمًا لا يجيء.
 *
 * وتبقى في `APPLICATION_STATUSES` لتُسمّى صفوفٌ قديمةٌ إن وُجدت، وفي قيد
 * القاعدة لأن حذفَ قيمةٍ من قيدٍ حيٍّ يحتاج هجرةً لا داعيَ لخطرها.
 */
export const LIVE_STATUSES: readonly ApplicationStatus[] =
  APPLICATION_STATUSES.filter((s) => s.value !== "referred");
