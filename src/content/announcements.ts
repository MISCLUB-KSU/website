/**
 * إعلانات النادي — أحدث الجلسات والفعاليات.
 *
 * ⚠️ **القائمة فارغة، والقسم يختفي من الرئيسية ما دامت كذلك.**
 *
 * هذا القسم هو ما يفرّق بين موقعٍ حيّ وموقعٍ مكتوب مرّة ونُسي: الزائر
 * يعرف أن النادي يعمل من آخر ثلاثة إعلانات، لا من صفحة «من نحن».
 *
 * **قاعدة تحكم هذا الملف:**
 *   · لا فعالية تُكتب قبل وقوعها بصيغة الماضي، ولا تبقى «قادمة» بعد مرورها.
 *   · لا صورة مُقدَّرة: من لا صورة له يُعرض بلا صورة، ولا تُستعار صورة
 *     فعالية أخرى «حتى تجهز».
 *   · أسماء الضيوف من خارج النادي تُذكر بإذنهم — وهم ليسوا أعضاءً،
 *     فقاعدة «لا أسماء أعضاء» لا تشملهم، لكن الإذن يبقى شرطًا.
 */

export type Announcement = {
  /** مفتاح ثابت — يبقى بعد النشر */
  id: string;
  title: string;
  /** سطران على الأكثر: ماذا جرى ولمن */
  summary: string;
  /** تاريخ الوقوع بصيغة `YYYY-MM-DD` — يُرتَّب به */
  date: string;
  /** مسار الصورة داخل `public/photos/` */
  image?: string;
  imageWidth?: number;
  imageHeight?: number;
  /** مكان الفعالية */
  venue?: string;
  /** المشروع الذي تتبعه، إن كانت ضمن مشروع */
  project?: string;
  /** رابط التفاصيل — داخلي أو خارجي */
  href?: string;
};

export const ANNOUNCEMENTS: readonly Announcement[] = [];

/** الأحدث أولًا — الترتيب من التاريخ لا من ترتيب الكتابة */
export const LATEST_ANNOUNCEMENTS = [...ANNOUNCEMENTS]
  .sort((a, b) => b.date.localeCompare(a.date))
  .slice(0, 3);
