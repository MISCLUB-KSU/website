/**
 * القيادات والخريجون.
 *
 * ⚠️⚠️ **القائمتان فارغتان عمدًا — لا تُملآن قبل قرار مكتوب.**
 *
 * قاعدة النادي القائمة: **لا اسم شخص في أي مادة يُنتجها المشروع** — لا
 * أعضاء ولا قادة لجان ولا رئاسة. مثبَّتة في `committees.ts` («أسماء رؤساء
 * اللجان والوحدات موجودة في العرض ولم تُنقل هنا، ولا تُنشر») وفي `README`،
 * ومصدرها قرار رئاسة النادي.
 *
 * ولذلك الأسماء **غير موجودة في المستودع أصلًا**: صفحات الملف التعريفي
 * ٥ و٢٢–٢٣ فيها أسماء وصور وسِيَر لأكثر من ٢٥ شخصًا، ولم يُنقل منها حرف.
 *
 * **ما ينقص قبل التعبئة:**
 *   ١. قرار من الرئاسة بنشر الأسماء — القاعدة الحالية تمنعها.
 *   ٢. **موافقة كل شخص** على نشر اسمه وصورته. النشر بلا إذنٍ بيانٌ شخصي
 *      يُنشر عن صاحبه لا له.
 *   ٣. الأسماء والصور نفسها، ولا تُنقل من الملف التعريفي بلا (١) و(٢).
 *
 * الواجهة تحذف القسم كاملًا ما دامت القائمة فارغة — لا عناوين معلّقة على
 * فراغ، ولا أسماء مُقدَّرة تُملأ «مؤقتًا».
 */

export type Person = {
  /** الاسم كما يريد صاحبه أن يُكتب */
  name: string;
  /** الدور — «رئيس اللجنة الإعلامية»، أو للخريج تخصّصه أو موقعه الحالي */
  role: string;
  /** دفعة التخرّج — للخريجين وحدهم */
  cohort?: string;
  /** سطر واحد بصوت صاحبه، لا وصفٌ يُكتب عنه */
  quote?: string;
  /** مسار الصورة داخل `public/people/` — تُترك فارغة فتُعرض البطاقة بلا صورة */
  photo?: string;
  /**
   * رابط حساب لينكدإن — اختياريٌّ عمدًا.
   *
   * يُترك فارغًا لمن لا يملك حسابًا أو لم يأذن بنشره، فتُعرض بطاقته بلا رابط
   * وتبقى على ارتفاع أخواتها. **لا يُخمَّن رابطٌ ولا يُبحث عنه** — يؤخذ من
   * صاحبه، فالرابط الخاطئ يشير إلى شخصٍ آخر باسم النادي.
   */
  linkedin?: string;
};

/** القيادات الحالية — رؤساء اللجان والوحدات */
export const LEADERS: readonly Person[] = [];

/** الخريجون — من مرّ بالنادي وتخرّج */
export const ALUMNI: readonly Person[] = [];
