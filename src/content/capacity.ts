/**
 * **مجموعُ ما يقبله النادي هذا الموسم — ٣٥٣ مقعدًا.**
 *
 * ⚠️ **ولا يُقرأ عددَ أعضاءٍ ممكنًا.** الصفُّ له `stage` واحدٌ وحالةٌ واحدة:
 * من قُبل عند رغبته توقّف سلّمُه، فالشخصُ يشغل **مقعدًا واحدًا** لا اثنين.
 * فليست ٣٥٣ سعةً تُملأ؛ هي حدودٌ عليا موزّعةٌ على جهاتٍ يتنافس عليها
 * ٢٧٥ متقدّمًا.
 *
 * ⚠️ **ومقعدُ المشروع مقعدُ عضويةٍ كمقعد اللجنة — بقرار الرئاسة في ٢٠
 * أغسطس ٢٠٢٦.** أي أن من قُبل في مشروعٍ عند رغبته الأولى يصير عضوًا فيه
 * **بلا لجنة**؛ و١٣٠ متقدّمًا وضعوا مشروعًا رغبةً أولى. عُرض هذا على
 * الرئاسة بأثره الرقميّ فأقرّته، ويُقال في اللوحة عند القبول حتى لا
 * تُفاجَأ به عند الإغلاق.
 */
export const CAPACITY_TOTAL = CAPACITY.reduce((sum, b) => sum + b.cap, 0);

const BY_VALUE = new Map<string, CapacityBucket>(
  CAPACITY.flatMap((bucket) => bucket.values.map((v) => [v, bucket] as const)),
);

/** سقفُ الجهة التي تقع فيها هذي الرغبة — و`undefined` لجهةٍ بلا سقف */
export function capacityOf(value: string): CapacityBucket | undefined {
  return BY_VALUE.get(value);
}

/**
 * **جهاتٌ مفتوحةٌ للتقديم بلا سقفٍ مسجَّل.**
 *
 * ⚠️ **تُحسب ولا يُرمى بها استثناء.** وحدةٌ جديدةٌ تُفتح في
 * `committees.ts` ولا تُذكر هنا تصير بلا سقفٍ صامتة، فيقبل قائدُها بلا
 * عدّاد. ورميُ استثناءٍ عند تحميل الوحدة يُبيّض شاشةَ اللوحة كلَّها على
 * سطرٍ ناقص — فتُقال في اللوحة بدل أن تُسقطها.
 */
export const UNCAPPED_PREFERENCES: readonly string[] = PREFERENCES.filter(
  (p) => p.open && !BY_VALUE.has(p.value),
).map((p) => p.value);

/**
 * **قيمٌ في الجدول أعلاه لا تقابلها رغبةٌ معرَّفة.**
 *
 * ⚠️ **وهذا هو الوجهُ الآخر للانحراف:** سلَجٌ يُعاد تسميتُه في
 * `committees.ts` يترك هنا سطرًا ميّتًا — سقفًا لا يعدّ أحدًا، وجهةً حيّةً
 * بلا سقف. والاثنان يظهران معًا في اللوحة.
 */
export const UNKNOWN_CAPACITY_VALUES: readonly string[] = CAPACITY.flatMap(
  (bucket) => bucket.values,
).filter((v) => !PREFERENCES.some((p) => p.value === v));


/* ── إرشادُ المقابلة ──────────────────────────────────────────────────── */

/**
 * **الحدُّ الموصى به للمدعوّين إلى المقابلة في كل جهة — مشتقٌّ من سقفها.**
 *
 * ⚠️ **كان رقمًا واحدًا (١٥) لكلّ الجهات، وقد ناقض السقوفَ يومَ وُضعت.**
 * وحدةُ الميزانية تقبل أربعةً و MISthon تقبل خمسين، والاثنتان كانتا تريان
 * «١٥» في الشريط نفسِه: فالأولى تُقابل أربعةَ أضعاف ما تقبل، والثانية
 * تُحرَم من ثلاثة أخماس مقاعدها لو التزمت الإرشاد.
 *
 * ⚠️ **والهامشُ نصفٌ لا صفر.** إرشادٌ يساوي السقفَ يعني أن كلَّ من قوبل
 * يُقبل — فلا اختيارَ أصلًا. والنصفُ يترك للقائد من يفاضل بينهم حيث يضغط
 * الطلب (الميزانية ٦ لأربعة مقاعد)، ويرفع القيدَ حيث لا يضغط (MISthon ٧٥
 * وطالبوه ٣٤ — فلا يبلغه أحد).
 *
 * ⚠️ **وعدّادٌ لا قفل، كسقف القبول.** الإدارة قالت حرفًا: «يمديك أقلّ، وفي
 * حالات استثناء يمديك أعلى». والرقمُ يُعرض ويُلوَّن ويُمرَّر.
 */
export const INTERVIEW_MARGIN = 1.5;

/**
 * إرشادُ جهةٍ لم تُعطَ سقفَ قبولٍ بعد — القيمةُ الموحَّدةُ القديمة.
 *
 * ⚠️ **لا تُحذف ظنًّا أن كلَّ جهةٍ لها سقف.** `UNCAPPED_PREFERENCES` أعلاه
 * تُحسب لأن الانحرافَ ممكن: وحدةٌ تُفتح ولا تُذكر هنا. فيبقى لها إرشادٌ
 * تعمل به حتى يُعطى سقفُها.
 */
export const INTERVIEW_GUIDE_FALLBACK = 15;

/* ── سقفُ المرحلة ─────────────────────────────────────────────────────── */

/**
 * **ما تقبله الجهةُ في المرحلة الأولى — لا أكثرُ من خمسةَ عشر.**
 *
 * ⚠️ **قرارُ الرئاسة في ٢٠ أغسطس ٢٠٢٦، وهو غيرُ سقف الموسم.** الفرزُ ثلاثُ
 * مراحل: أصحابُ الرغبة الأولى، ثم الثانية، ثم الثالثة. ولو ملأت جهةٌ سقفَ
 * موسمها كلَّه من الرغبات الأولى لَما بقي لمن نزل إليها شيءٌ — وهو نقضٌ
 * لمعنى السلّم أصلًا: المرحلةُ الثانيةُ تفتح على مقاعدَ لا وجود لها.
 *
 * ⚠️ **ويُؤخذ الأصغرُ من الاثنين لا الخمسةَ عشرَ حرفيًّا.** وحدةُ الميزانية
 * سقفُ موسمها **أربعة**؛ فـ«خمسةَ عشرَ في المرحلة الأولى» عندها يعني
 * ثلاثةَ أضعافِ ما تملك. فالسقفُ الفعليّ `min(15, cap)`: الميزانية ٤،
 * والأرشيف ٧، والتصوير ١٠، وما فوقها ١٥.
 */
export const PHASE_ONE_CAP = 15;

/**
 * سقفُ القبول الفعليّ عند مرحلةٍ بعينها.
 *
 * ⚠️ **وما بعد الأولى يرجع إلى سقف الموسم لا يتضاعف.** العدُّ تراكميّ —
 * `accepted` تجمع من قُبل في كلّ المراحل — فسقفُ المرحلة الثانية هو ما
 * بقي من الموسم، لا خمسةَ عشرَ جديدة.
 */
export function capAtPhase(cap: number, phase: number): number {
  return phase <= 1 ? Math.min(PHASE_ONE_CAP, cap) : cap;
}

/** إرشادُ المقابلة لسقفٍ بعينه — ⌈السقف × ١٫٥⌉ */
export function guideFor(cap: number): number {
  return Math.ceil(cap * INTERVIEW_MARGIN);
}

/** كم يُدعى إلى المقابلة في الجهة التي تقع فيها هذي الرغبة، عند مرحلةٍ ما */
export function interviewGuide(value: string, phase: number): number {
  const bucket = capacityOf(value);
  return bucket
    ? guideFor(capAtPhase(bucket.cap, phase))
    : INTERVIEW_GUIDE_FALLBACK;
}
