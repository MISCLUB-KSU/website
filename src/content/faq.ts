export const FAQ_CATEGORIES = ["العضوية", "التقديم"] as const;

export type FaqCategory = (typeof FAQ_CATEGORIES)[number];

export type FaqItem = {
  question: string;
  /** فقرات الجواب — سطر أو سطران، لا مقال */
  answer: readonly string[];
  /** رابط يكمل الجواب داخل الموقع */
  link?: { label: string; href: string };
  /** فئة العرض — انظر `FAQ_CATEGORIES` أعلاه */
  category: FaqCategory;
};

/** أسئلة فئةٍ بعينها بترتيب ورودها في `FAQ`. */
export function faqByCategory(category: FaqCategory): readonly FaqItem[] {
  return FAQ.filter((item) => item.category === category);
}

