/**
 * مشاريع النادي — مستخرجة من عرض "اجتماع قادة المشاريع".
 *
 * هذي البيانات هي محرك نموذج التسجيل: الطالب يتصفح المشاريع،
 * ويقدّم على المشروع اللي يناسبه — بدل فورم عضوية عام.
 *
 * ملاحظة خصوصية: أسماء القادة والفرق موجودة في العرض لكنها **لم تُنقل هنا**
 * ولن تُنشر إلا بعد موافقة رئاسة النادي وأصحابها.
 *
 * حالة التقديم مبدئيًا "closed" لكل المشاريع — تُفتح من لوحة الإدارة
 * عند بدء التسجيل، فتُتاح المشاريع كلها في اللحظة نفسها.
 */

import type { CustomQuestion } from "./questions";

/**
 * حالتان لا ثالثة لهما — بقرار رئاسة النادي:
 * يُفتح التقديم فتُتاح كل المشاريع دفعةً واحدة، ويُغلق فتُقفل كلها.
 * لا حالة "قريبًا" لأنها تجعل الطالب ينتظر شيئًا بلا موعد.
 */
export type ApplicationState = "open" | "closed";

export type ProjectProgram = {
  name: string;
  /** لون البرنامج — يبقى فارغًا حتى يصل من عرض قادة المشاريع */
  accent?: string;
  nameAr?: string;
  description: string;
};

export type ProjectStat = {
  value: string;
  label: string;
};

export type Project = {
  /**
   * هل لهذي الجهة **رابطُ تقديمٍ مباشر**؟
   *
   * قائدٌ عنده جمهورٌ خارج النادي يرسل لهم `‎/join/project/<slug>` فيفتح
   * تقديمَ جهته وحدها بلا خطوة الرغبات الثلاث.
   *
   * ⚠️ **راية بيانات لا شرط شيفرة**، ليطفئها القائد أو الرئاسة بسطرٍ حين
   * يمتلئ نصيبه. وغيابُها = لا رابط، فالافتراضُ الآمن هو المنع.
   */
  directLink?: boolean;

  /**
   * مسار شعار المشروع داخل `public/projects/`.
   *
   * يبقى فارغًا حتى يصل الملف الأصلي، فتُعرض شريحة الميلان بدلًا منه.
   * ولا يُعاد رسم شعار بالتقدير — انظر `project-mark.tsx`.
   */
  markSrc?: string;
  slug: string;
  name: string;
  tagline?: string;
  summary: string;
  vision?: string;
  mission?: string;
  /** البرامج أو المسارات داخل المشروع */
  programs?: readonly ProjectProgram[];
  /** أرقام حقيقية فقط — لا أرقام تزيينية */
  stats?: readonly ProjectStat[];
  /** هل هو مبادرة داخلية أم خارجية */
  isExternal?: boolean;
  /**
   * لون المشروع — كل مشروع علامة فرعية لها طبقة ألوان خاصة تختلف عن النادي.
   *
   * قاعدة الاستعمال، وإلا انهارت هوية النادي إلى ألوان متناثرة:
   * داخل فضاء النادي (الشريط، البطاقات، التذييل) لا يظهر هذا اللون إلا
   * كعلامة صغيرة تسبق الاسم. أما الطبقة الكاملة فلا تُطبَّق إلا داخل
   * فضاء المشروع نفسه.
   *
   * القيم لم تُعتمد بعد — تُملأ من الهوية الرسمية لكل مشروع.
   */
  accent?: string;
  applicationState: ApplicationState;
  /** أسئلة قائد المشروع — تظهر لمن اختاره ضمن رغباته. انظر `questions.ts` */
  questions?: readonly CustomQuestion[];
  /**
   * توجيه سعود: "تضغط على المشروع يوديك صفحة المشروع (حتى لو موقع ثاني)".
   *
   * لو المشروع صار له موقعه المستقل، نحط رابطه هنا فتفتح البطاقة عليه مباشرة.
   * ولو فاضي، نعرض صفحة المشروع داخل موقع النادي — فنقدر نطلق الحين
   * ونربط المواقع المستقلة لاحقًا بدون أي تغيير في الواجهة.
   */
  externalUrl?: string;
};

/** الوجهة الصحيحة لبطاقة المشروع — خارجية إن وُجدت، وإلا داخلية */
export function projectHref(project: Project): string {
  return project.externalUrl ?? `/projects/${project.slug}`;
}

