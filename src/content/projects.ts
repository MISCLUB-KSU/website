/**
 * مشاريع النادي — مستخرجة من عرض "اجتماع قادة المشاريع".
 *
 * هذي البيانات هي محرك نموذج التسجيل: الطالب يتصفح المشاريع،
 * ويقدّم على المشروع اللي يناسبه — بدل فورم عضوية عام.
 *
 * ملاحظة خصوصية: أسماء القادة والفرق موجودة في العرض لكنها **لم تُنقل هنا**
 * ولن تُنشر إلا بعد موافقة رئاسة النادي وأصحابها.
 *
 * ⚠️ **حالةُ التقديم `open` للمشاريع الداخلية الخمسة** (١٥ أغسطس ٢٠٢٦،
 * بقرار الإدارة: «المشاريع افتحها كلها»). وكانت `closed` لها جميعًا —
 * وصفًا لا أثرَ له، إذ كانت الراية تُقرأ في سطرِ الواجهة وحده والمشاريعُ
 * تستقبل. فصارت قفلًا حقيقيًّا (انظر `OPEN_PREFERENCES` في
 * `preferences.ts`)، ثم فُتحت الخمسةُ صراحةً — فالوصفُ والأثرُ متّفقان.
 *
 * وتُقلب بتعديل سطرٍ هنا لا من لوحة الإدارة: لا شاشةَ لها اليوم.
 *
 * ⚠️ **وواحدةٌ تبقى `closed`: `learnx`** — مبادرةٌ نُفِّذت ولا يستقبل
 * النموذجُ طلباتٍ لها. فالإغلاق وصفٌ صادق لها لا قرارُ موسم.
 *
 * وكان معها `technnovate` و`mis-community`، أُضيفتا في ١٦ أغسطس وحُذفتا في
 * ١٧ — «هذي قديمة وانتهت، شلها». والفرقُ عن `learnx` أنّ تلك يُراد بقاؤها
 * معروضةً في صفحة المشاريع، وهاتان لا.
 *
 * وكانت `learnx` تُستبعَد بـ`isExternal` قبل ١٦ أغسطس؛
 * ورُفعت الرايةُ حين صُحِّح تصنيفُها (التعليل عند تعريفها)، فصار الإخراجُ
 * من `closed` وحدها — وهي السبب الصحيح.
 *
 * ⚠️ **ولا مشروعَ `isExternal` اليوم.** الحقلُ باقٍ في النوع ويُفحص في
 * `preferences.ts` و`preference-guide.tsx`، فلو وصلت مبادرةٌ ليست لنا يومًا
 * عملت الحيلةُ كما هي — لكنّه اليوم لا يُقصي أحدًا، والإقصاءُ كلُّه من
 * `applicationState`.
 */

