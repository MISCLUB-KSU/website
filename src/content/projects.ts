  slug: string;
  name: string;
  tagline?: string;
  summary: string;
  vision?: string;
  mission?: string;
  /** البرامج أو المسارات داخل المشروع */
  programs?: readonly ProjectProgram[];
  /** أرقام حقيقية فقط — لا أرقام تزيينية */
  stats?: readonly ProjectStat[];
  /** هل هو مبادرة داخلية أم خارجية */
  isExternal?: boolean;
  /**
   * **بابُ التقديم حين لا يكون عندنا.**
   *
   * جهةٌ يُعرَّف بها في دليل الرغبات، لكنّ التسجيل عليها يجري في قناتها هي.
   *
   * ⚠️ و`applicationState: "closed"` وحدها لا تكفي لوصف هذي الحال: تلك تقول
   * «لا يُقدَّم عليها **هنا**»، فيقرأ الطالبُ صمتَنا «انتهت» — ويضيع بابٌ
   * مفتوح. فهذا الحقل يقول أين البابُ بدل أن يُسكَت عنه.
   *
   * ⚠️ **ووجودُه لا يفتح التقديم عندنا.** الجهةُ تبقى خارج بطاقات الاختيار
   * وخارج `OPEN_PREFERENCES` — تُعرَض تعريفًا ورابطًا لا خانةَ اختيار.
   */
